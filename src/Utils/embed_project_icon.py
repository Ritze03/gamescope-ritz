#!/usr/bin/env python3
# Turns icon-256.png (the project icon, exported from icon.svg with
# `rsvg-convert -w 256 -h 256 icon.svg -o icon-256.png`) into a C header holding
# its bytes. Same generated-header shape as Overlay/embed_changelog.py. Used by
# Utils/TaskbarIcon.cpp. Invoked as a meson custom_target (src/meson.build).
import sys


def main():
    if len( sys.argv ) != 3:
        sys.stderr.write( "usage: embed_project_icon.py <icon.png> <output.h>\n" )
        return 1
    with open( sys.argv[1], "rb" ) as f:
        data = f.read()
    with open( sys.argv[2], "w" ) as f:
        f.write( "// Auto-generated by embed_project_icon.py -- do not edit.\n#pragma once\n" )
        f.write( "static const unsigned char g_ProjectIcon_Data[] = {\n" )
        for i in range( 0, len( data ), 20 ):
            f.write( ",".join( str( b ) for b in data[i:i + 20] ) + ",\n" )
        f.write( "};\n" )
        f.write( "static const unsigned int g_ProjectIcon_Size = {}u;\n".format( len( data ) ) )
    return 0


sys.exit( main() )
